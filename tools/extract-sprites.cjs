#!/usr/bin/env node
/*
 * extract-sprites.cjs — pulls the pixel-art matrices out of the original
 * Burnline bundle.
 *
 * The original never ships images for its characters: it stores them as ASCII
 * matrices (`rows` of characters, each mapped to a hex colour in `pal`) and
 * paints them into an offscreen canvas at integer scale. That payload is exactly
 * what we want, so this copies it verbatim rather than redrawing anything.
 *
 *   foes  = Kn   35 enemies, 10 zones (slums/servers/sewer/arcology/foundry/
 *                desert/frozen/jungle/orbital/kernel), each with rows + pal
 *   heroes= rr   4 playable fighters with 14-21 pose sheets + pal + rim
 *
 * Usage: node tools/extract-sprites.cjs /path/to/pretty.js
 * The generated file is committed; re-run only if the upstream bundle changes.
 */
const fs = require('fs');
const path = require('path');

const srcPath = process.argv[2];
if (!srcPath) {
  console.error('usage: node tools/extract-sprites.cjs <pretty-bundle.js>');
  process.exit(1);
}
const src = fs.readFileSync(srcPath, 'utf8');

/** Bracket-match an array/object literal that starts at `name = <open>`. */
function grab(name, open) {
  const at = src.indexOf(name + ' = ' + open);
  if (at < 0) throw new Error('could not find ' + name);
  const start = src.indexOf(open, at + name.length);
  let depth = 0;
  let i = start;
  let str = null;
  let esc = false;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (str) {
      if (esc) esc = false;
      else if (ch === '\\') esc = true;
      else if (ch === str) str = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') {
      str = ch;
      continue;
    }
    if (ch === open) depth++;
    else if (ch === (open === '[' ? ']' : '}')) {
      depth--;
      if (depth === 0) return src.slice(start, i + 1);
    }
  }
  throw new Error('unterminated literal for ' + name);
}

const evalLit = (lit) => new Function('return ' + lit)();

// --- foes: Kn = [ { zone, name, rows, pal, fly, big, scale }, ... ] ---------
const foes = evalLit(grab('Kn', '['));
if (foes.length < 30) throw new Error('foe table looks wrong: ' + foes.length);

// --- heroes: qn/tr are pose sheets, nr is the first fighter, rr is the roster
const qn = evalLit(grab('qn', '{'));
const tr = evalLit(grab('tr', '{'));
const nr = new Function('qn', 'tr', 'return ' + grab('nr', '{'))(qn, tr);
const heroes = new Function('qn', 'tr', 'nr', 'const rr = ' + grab('rr', '[') + '; return rr;')(qn, tr, nr);
if (heroes.length < 4) throw new Error('hero roster looks wrong: ' + heroes.length);

// --- validate, then emit ----------------------------------------------------
const problems = [];
const checkRows = (what, rows) => {
  if (!Array.isArray(rows) || !rows.length) return problems.push(what + ': no rows');
  const w = rows[0].length;
  if (rows.some((r) => r.length !== w)) problems.push(what + ': ragged rows');
  if (w > 40 || rows.length > 40) problems.push(what + ': implausibly large');
};
for (const f of foes) {
  checkRows('foe ' + f.zone + '/' + f.name, f.rows);
  if (!f.pal || !Object.keys(f.pal).length) problems.push('foe ' + f.name + ': no palette');
}
for (const h of heroes) {
  for (const [pose, rows] of Object.entries(h.poses)) checkRows('hero ' + h.id + '/' + pose, rows);
  if (!h.pal || !h.rim) problems.push('hero ' + h.id + ': no palette/rim');
}
if (problems.length) {
  console.error(problems.slice(0, 10).join('\n'));
  throw new Error(problems.length + ' problems in the sprite tables');
}

const zones = [...new Set(foes.map((f) => f.zone))];
const slimFoes = foes.map((f) => ({
  zone: f.zone,
  name: f.name,
  rows: f.rows,
  pal: f.pal,
  fly: !!f.fly,
  big: !!f.big,
  scale: f.scale || 1,
}));
const slimHeroes = heroes.map((h) => ({
  id: h.id,
  name: h.name,
  style: h.style,
  pal: h.pal,
  rim: h.rim,
  accent: h.accent,
  poses: h.poses,
}));

const out = `/*
 * sprites.js — GENERATED by tools/extract-sprites.cjs from the original Burnline
 * bundle. Do not edit by hand.
 *
 * ${slimFoes.length} foes across ${zones.length} zones (${zones.join(', ')})
 * ${slimHeroes.length} fighters (${slimHeroes.map((h) => h.name).join(', ')})
 *
 * Each entry is an ASCII pixel matrix: every non-dot character is a pixel whose
 * colour comes from \`pal\`. BL.Stage paints them at integer scale.
 */
(function (BL) {
  'use strict';

  BL.SPRITE_DATA = {
    zones: ${JSON.stringify(zones)},
    foes: ${JSON.stringify(slimFoes)},
    heroes: ${JSON.stringify(slimHeroes)},
  };
})(window.BL = window.BL || {});
`;

const dest = path.resolve(process.argv[3] || 'js/data/sprites.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
const kb = (fs.statSync(dest).size / 1024).toFixed(1);
console.log(problems.length ? problems.join('\n') : 'sprites ok');
console.log(`${slimFoes.length} foes / ${slimHeroes.length} heroes -> ${dest} (${kb} KB)`);
